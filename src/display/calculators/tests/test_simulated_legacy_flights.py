class FaiPrecisionProcedureTurnTest(ScenarioCase):
    """Turns of 160 degrees need a procedure turn: pass the gate, turn the long way round, come back."""

    task_type = PRECISION
    scorecard_shortcut = "FAI Precision"
    legs = STEEP_LEGS

    def test_correctly_flown_procedure_turns_have_no_penalties(self):
        self.build()
        track, result = self.fly(ProcedureTurn("TP1"), ProcedureTurn("TP2"))
        self.assertNoPenalties(result)
        for gate in ("SP", "TP1", "TP2", "FP"):
            self.assertLessEqual(abs(timing_error(result, self.task, gate)), 1.0, gate)

    def test_turning_the_short_way_instead_is_a_missing_procedure_turn(self):
        self.build()
        track, result = self.fly(ProcedureTurn("TP1", direction="right"), ProcedureTurn("TP2"))
        penalty = self.scorecard.get_procedure_turn_penalty_for_gate_type("tp")
        self.assertGreater(penalty, 0)
        self.assertEqual(penalties(result), [(PROCEDURE_TURN_SCORE, "TP1", float(penalty))])
        self.assertEqual(result.score, penalty)

    def test_missing_the_procedure_turn_at_the_second_turn_point(self):
        self.build()
        track, result = self.fly(ProcedureTurn("TP1"), ProcedureTurn("TP2", direction="left"))
        penalty = self.scorecard.get_procedure_turn_penalty_for_gate_type("tp")
        self.assertEqual(penalties(result), [(PROCEDURE_TURN_SCORE, "TP2", float(penalty))])

    def test_a_late_gate_before_a_correct_procedure_turn_costs_only_the_timing(self):
        self.build()
        track, result = self.fly(TimeOffset("TP1", 5), ProcedureTurn("TP1"), ProcedureTurn("TP2"))
        error = timing_error(result, self.task, "TP1")
        self.assertAlmostEqual(error, 5, delta=1.0)
        self.assertEqual(penalties(result), [(GATE_SCORE, "TP1", timing_penalty(self.scorecard, "tp", error))])

    def test_same_track_gives_identical_messages(self):
        self.build()
        self.assertDeterministic(ProcedureTurn("TP1", direction="right"), ProcedureTurn("TP2"))
