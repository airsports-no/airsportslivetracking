from display.utilities.coordinate_utilities import project_position_lat_lon
from display.utilities.navigation_task_type_definitions import PRECISION

START_POINT = (60.0, 11.0)
BACKTRACKING = "backtracking"
GATE_SCORE = "gate_score"
CORRIDOR = "outside_corridor"
PROCEDURE_TURN_SCORE = "procedure_turn"
PROHIBITED = "inside_prohibited_zone_"
PENALTY_ZONE = "inside_penalty_zone_"

# Gentle turns (+15 and -15 degrees): cutting a corner stays inside a 1 NM corridor.
GENTLE_LEGS = ((90.0, 6000.0), (105.0, 5000.0), (90.0, 6000.0))
# Turns of 160 degrees right and left: both turn points need a procedure turn.
STEEP_LEGS = ((90.0, 8000.0), (250.0, 8000.0), (90.0, 8000.0))
# Turns of 70 degrees right and left: cutting a corner passes outside the gate line.
SHARP_LEGS = ((90.0, 6000.0), (160.0, 5000.0), (90.0, 6000.0))
CORRIDOR_WIDTH_NM = 1.0
HALF_CORRIDOR_M = CORRIDOR_WIDTH_NM * 1852.0 / 2.0


