def leg_point(along: float, across: float = 0.0) -> tuple[float, float]:
    """(lat, lon) `along` metres east of the start point and `across` metres to the right (south) of the first leg."""
    point = project_position_lat_lon(START_POINT, 90.0, along)
    return project_position_lat_lon(point, 180.0, across) if across else point


def zone_feature(kind: str, name: str, along: tuple[float, float], across: tuple[float, float]) -> dict:
    """A rectangular zone ("prohibited" or "penalty") beside the first leg, as the route editor saves it."""
    corners = [
        leg_point(along[0], across[0]),
        leg_point(along[1], across[0]),
        leg_point(along[1], across[1]),
        leg_point(along[0], across[1]),
    ]
    coordinates = [[lon, lat] for lat, lon in corners]
    coordinates.append(coordinates[0])
    return {
        "type": "Feature",
        "properties": {"id": str(uuid.uuid4()), "name": name, "polygonType": kind, "featureType": "zone"},
        "geometry": {"type": "Polygon", "coordinates": [coordinates]},
    }


def takeoff_gate_feature(along: float, half_length_m: float = 150.0) -> dict:
    """A take-off gate across the extended first leg, `along` metres east of the start point (negative: before it)."""
    first, second = leg_point(along, -half_length_m), leg_point(along, half_length_m)
    return {
        "type": "Feature",
        "properties": {
            "id": str(uuid.uuid4()),
            "name": "Takeoff 1",
            "gateType": "takeoff",
            "featureType": "takeoff_gate",
        },
        "geometry": {"type": "LineString", "coordinates": [[first[1], first[0]], [second[1], second[0]]]},
    }


def route_geojson(legs=GENTLE_LEGS, hidden=(), extra_features=()) -> dict:
    """A route of SP, TP1..TPn and FP. `hidden` names turn points that become hidden (secret) gates."""
    geojson = precision_route_geojson(legs=legs)
    for feature in geojson["features"]:
        if feature["properties"].get("name") in hidden:
            feature["properties"]["pointType"] = "secret"
    geojson["features"].extend(extra_features)
    return geojson


# ---------------------------------------------------------------------------------------------------------------------
# Expectations computed from the scorecard and the generated track
# ---------------------------------------------------------------------------------------------------------------------


def timing_error(result, task, gate: str) -> float:
    """Seconds the gate was passed after its expected time (negative: early), as the calculators measured it."""
    passed = result.gate_passing_times.get(gate)
    if passed is None:  # take-off gates are not among the route gates; their crossing is in the score message
        passed = next(m.actual for m in result.messages if m.gate.name == gate and m.actual)
    return (passed - task.gate_times[gate]).total_seconds()


def timing_penalty(scorecard, gate_type: str, error: float) -> float:
    """The rule: nothing within the grace period, then round(|error| - grace) x points per second, capped."""
    gate = scorecard.get_gate_scorecard(gate_type)
    grace = gate.graceperiod_after if error > 0 else gate.graceperiod_before
    if abs(error) < grace:
        return 0
    penalty = round(abs(error) - grace) * gate.penalty_per_second
    return min(penalty, gate.maximum_penalty) if gate.maximum_penalty > 0 else penalty


def corridor_penalty(scorecard, outside_seconds: float) -> float:
    """The rule: the corridor penalty per second for every second outside beyond the grace time, capped if set."""
    seconds = round(outside_seconds - scorecard.corridor_grace_time)
    if seconds <= 0:
        return 0
    penalty = seconds * scorecard.corridor_outside_penalty
    cap = scorecard.corridor_maximum_penalty
    return min(penalty, cap) if cap > 0 else penalty


def backtracking_penalty(scorecard) -> float:
    cap = scorecard.backtracking_maximum_penalty
    return min(scorecard.backtracking_penalty, cap) if cap > 0 else scorecard.backtracking_penalty


def penalties(result) -> list[tuple[str, str, float]]:
    """(score type, gate, points) of every message that costs points, in the order they were given."""
    return [
        (message.score_type, message.gate.name, float(message.score)) for message in result.messages if message.score
    ]


def inside_runs(task, positions, zone: dict) -> list[tuple[datetime.datetime, datetime.datetime, datetime.datetime]]:
    """Every stay inside the zone polygon: (first sample inside, last sample inside, first sample outside after it)."""
    projector = task.projector
    ring = zone["geometry"]["coordinates"][0]
    polygon = Polygon(
        [(p.projected_x, p.projected_y) for p in (projector.project_point(lat, lon) for lon, lat in ring)]
    )
    inside = []
    for position in positions:
        projected = projector.project_point(position.latitude, position.longitude)
        inside.append(polygon.contains(Point(projected.projected_x, projected.projected_y)))
    runs = []
    index = 0
    while index < len(positions):
        if not inside[index]:
            index += 1
            continue
        first = index
        while index < len(positions) and inside[index]:
            index += 1
        runs.append((positions[first].time, positions[index - 1].time, positions[min(index, len(positions) - 1)].time))
    return runs


def seconds_beyond(task, positions, start: str, end: str, half_width_m: float) -> float:
    """Seconds between the first and the last sample farther than `half_width_m` from the straight line start -> end
    in the first excursion of the track, looking only at the flight between the two gates' times."""
    projector = task.projector
    names = [w.name for w in task.effective_waypoints]
    a_wp, b_wp = (task.effective_waypoints[names.index(name)] for name in (start, end))
    a, b = (projector.project_point(w.latitude, w.longitude) for w in (a_wp, b_wp))
    ax, ay, bx, by = a.projected_x, a.projected_y, b.projected_x, b.projected_y
    length = math.hypot(bx - ax, by - ay)
    first = last = None
    for position in positions:
        if not task.gate_times[start] <= position.time <= task.gate_times[end]:
            continue
        p = projector.project_point(position.latitude, position.longitude)
        lateral = abs((p.projected_x - ax) * (by - ay) - (p.projected_y - ay) * (bx - ax)) / length
        if lateral > half_width_m:
            first = first or position.time
            last = position.time
        elif first is not None:
            break
    assert first is not None, "The track never left the corridor"
    return (last - first).total_seconds()


class ScenarioCase(TestCase):
    """Common helpers. Subclasses set the task type, scorecard and route, and call `self.build()`."""

    task_type = PRECISION
    scorecard_shortcut = ""
    legs = GENTLE_LEGS
    hidden = ()
    extra_features = ()
    build_options: dict = {}

    def build(self, *, legs=None, hidden=None, features=None, **overrides):
        options = {**self.build_options, **overrides}
        self.task = build_task(
            route_geojson(
                legs or self.legs,
                self.hidden if hidden is None else hidden,
                self.extra_features if features is None else features,
            ),
            task_type=self.task_type,
            scorecard_shortcut=self.scorecard_shortcut,
            name=f"{self.__class__.__name__} task",
            **options,
        )
        self.scorecard = self.task.navigation_task.scorecard
        return self.task

    def fly(self, *deviations, **options):
        track = self.task.generate_track(list(deviations), **options)
        return track, self.task.run(track)

    def fly_from_takeoff_gate(self, *deviations):
        """Like `fly`, for a task with a take-off gate: the flight starts by crossing it at its time."""
        gate = self.task.route.takeoff_gates[0]
        waypoints = [waypoint(gate.name, gate.latitude, gate.longitude, 0.1), *self.task.effective_waypoints]
        track = generate_track(
            waypoints, self.task.gate_times, deviations=list(deviations), projector=self.task.projector
        )
        return track, self.task.run(track)

    def gate_type(self, gate: str) -> str:
        return next(w.type for w in self.task.effective_waypoints if w.name == gate)

    def assertNoPenalties(self, result):
        self.assertEqual(penalties(result), [])
        self.assertEqual(result.score, self.scorecard.initial_score)
        self.assertEqual(result.missed_gates, [])

    def assertDeterministic(self, *deviations):
        track = self.task.generate_track(list(deviations))
        first, second = self.task.run(track), self.task.run(track)
        self.assertTrue(first.messages)
        self.assertEqual(first.summary(), second.summary())
        self.assertEqual(first.score, second.score)
        self.assertEqual(first.score_by_type, second.score_by_type)
        self.assertEqual(first.gate_passing_times, second.gate_passing_times)


