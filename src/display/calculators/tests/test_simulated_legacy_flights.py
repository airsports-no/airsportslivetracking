"""Scenario tests: synthetic flights through the real calculators for the legacy task types.

Precision (FAI Precision with and without procedure turns), ANR corridor (FAI ANR 2022) and Air Sports Race (the 2025
Annex 9 scorecard). Each flight is generated by the simulator in flight_simulator.py, fed through the calculators and
the real score application, and the resulting penalties are compared with what the scorecard's own values and the rules
say they should be. These tests describe today's behaviour of task types that are trusted; they validate the simulator
and pin the behaviour before the scoring code is refactored.

Gate crossings are reported by the calculators in whole seconds, so the observed timing error of a gate differs from
the offset the track was given by up to a second. The expected timing penalty is therefore computed from the observed
error (`timing_error`) with the rule (round(|error| - grace) x points per second, capped), and the track offset is
checked separately to be what was asked for.
"""

