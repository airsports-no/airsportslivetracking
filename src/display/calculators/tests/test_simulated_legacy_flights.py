class PrecisionScenarios:
    """Scenarios shared by both precision scorecards, flown on a route without turns that need a procedure turn."""

    task_type = PRECISION

    def test_perfect_flight_has_no_penalties(self):
        self.build()
        track, result = self.fly()
        self.assertNoPenalties(result)
        for gate in ("SP", "TP1", "TP2", "FP"):
            self.assertLessEqual(abs(timing_error(result, self.task, gate)), 1.0, gate)

    def test_gates_passed_a_little_early_and_late_are_free(self):
        self.build()
        track, result = self.fly(TimeOffset("TP1", 0.5), TimeOffset("TP2", -0.5))
        self.assertAlmostEqual(timing_error(result, self.task, "TP1"), 0.5, delta=1.0)
        self.assertAlmostEqual(timing_error(result, self.task, "TP2"), -0.5, delta=1.0)
        self.assertNoPenalties(result)

    def test_one_gate_late_and_another_early_outside_the_grace_period(self):
        self.build()
        track, result = self.fly(TimeOffset("TP1", 5), TimeOffset("TP2", -5))
        late, early = timing_error(result, self.task, "TP1"), timing_error(result, self.task, "TP2")
        self.assertAlmostEqual(late, 5, delta=1.0)
        self.assertAlmostEqual(early, -5, delta=1.0)
        grace = self.scorecard.get_gate_scorecard("tp")
        self.assertGreater(late, grace.graceperiod_after)
        self.assertLess(early, -grace.graceperiod_before)
        expected = [
            (GATE_SCORE, "TP1", timing_penalty(self.scorecard, "tp", late)),
            (GATE_SCORE, "TP2", timing_penalty(self.scorecard, "tp", early)),
        ]
        self.assertTrue(all(points > 0 for _, _, points in expected))
        self.assertEqual(penalties(result), expected)
        self.assertEqual(result.score, sum(points for _, _, points in expected))

    def test_late_penalty_is_capped_at_the_maximum(self):
        self.build()
        track, result = self.fly(TimeOffset("TP1", 60))
        gate = self.scorecard.get_gate_scorecard("tp")
        error = timing_error(result, self.task, "TP1")
        self.assertGreater((round(error) - gate.graceperiod_after) * gate.penalty_per_second, gate.maximum_penalty)
        self.assertEqual(penalties(result), [(GATE_SCORE, "TP1", float(gate.maximum_penalty))])
        self.assertEqual(result.score, gate.maximum_penalty)

    def test_early_penalty_is_capped_at_the_maximum(self):
        self.build()
        track, result = self.fly(TimeOffset("TP2", -60))
        gate = self.scorecard.get_gate_scorecard("tp")
        self.assertEqual(penalties(result), [(GATE_SCORE, "TP2", float(gate.maximum_penalty))])
        self.assertEqual(result.score, gate.maximum_penalty)

    def test_gate_missed_sideways_costs_the_missed_penalty(self):
        self.build()
        track, result = self.fly(MissGate("TP1"))
        missed = self.scorecard.get_gate_scorecard("tp").missed_penalty
        self.assertEqual(result.missed_gates, ["TP1"])
        self.assertEqual(penalties(result), [(GATE_SCORE, "TP1", float(missed))])
        self.assertEqual(result.score, missed)

    def test_gate_skipped_costs_the_missed_penalty(self):
        self.build(legs=SHARP_LEGS)  # cutting a gentle corner would still cross the gate line
        track, result = self.fly(SkipGate("TP1"))
        missed = self.scorecard.get_gate_scorecard("tp").missed_penalty
        self.assertEqual(result.missed_gates, ["TP1"])
        self.assertIsNone(result.gate_passing_times["TP1"])
        self.assertEqual(penalties(result), [(GATE_SCORE, "TP1", float(missed))])
        self.assertEqual(result.score, missed)

    def test_flying_backwards_longer_than_the_grace_time_is_backtracking(self):
        self.build()
        seconds = self.scorecard.backtracking_grace_time_seconds * 2
        track, result = self.fly(Reverse("SP", seconds=seconds))
        self.assertEqual(penalties(result), [(BACKTRACKING, "SP", float(backtracking_penalty(self.scorecard)))])
        self.assertEqual(result.score, backtracking_penalty(self.scorecard))
        self.assertEqual(result.missed_gates, [])

    def test_flying_backwards_shorter_than_the_grace_time_is_free(self):
        self.build()
        seconds = self.scorecard.backtracking_grace_time_seconds - 2
        track, result = self.fly(Reverse("SP", seconds=seconds))
        self.assertNoPenalties(result)

    def test_a_full_orbit_is_backtracking(self):
        self.build()
        track, result = self.fly(Orbit("TP1", radius_m=300))
        self.assertEqual(penalties(result), [(BACKTRACKING, "TP1", float(backtracking_penalty(self.scorecard)))])
        self.assertEqual(result.missed_gates, [])

    def test_same_track_gives_identical_messages(self):
        self.build()
        self.assertDeterministic(TimeOffset("TP1", 5), Reverse("SP", seconds=10))


